import 'dart:convert';
import 'dart:io';

const _unicodeVersion = '17.0.0';
const _outputPath = 'lib/src/upper_case_mapping.dart';

/// Writes [_outputPath], the uppercase of each code point as ECMAScript's
/// `toUpperCase` defines it: the unconditional mapping of `SpecialCasing.txt`,
/// else the simple one of `UnicodeData.txt`, from Unicode [_unicodeVersion].
Future<void> main() async {
  final mapping = <int, List<int>>{};
  for (final fields in await _read('UnicodeData.txt')) {
    if (fields[12].isNotEmpty) mapping[_code(fields[0])] = [_code(fields[12])];
  }
  for (final fields in await _read('SpecialCasing.txt')) {
    final conditional = fields.length > 4 && fields[4].isNotEmpty;
    if (!conditional) {
      mapping[_code(fields[0])] = fields[3].split(' ').map(_code).toList();
    }
  }
  mapping.removeWhere((code, upper) => upper.length == 1 && upper[0] == code);

  final codes = mapping.keys.toList()..sort();
  final output = StringBuffer()
    ..writeln(
      '// Generated by `dart run tool/upper_case_mapping.dart` from Unicode '
      '$_unicodeVersion, do not edit.',
    )
    ..writeln()
    ..writeln('/// The uppercase of each code point that has one, as')
    ..writeln("/// JavaScript's `toUpperCase` gives it.")
    ..writeln('const upperCaseMapping = <int, String>{');
  for (final code in codes) {
    final upper = mapping[code]!.map((c) => '\\u{${_hex(c)}}').join();
    output.writeln("  0x${_hex(code)}: '$upper',");
  }
  output.writeln('};');

  final root = File.fromUri(Platform.script).parent.parent;
  File('${root.path}/$_outputPath').writeAsStringSync(output.toString());
}

Future<List<List<String>>> _read(String name) async {
  final url = 'https://www.unicode.org/Public/$_unicodeVersion/ucd/$name';
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(Uri.parse(url))).close();
    if (response.statusCode != HttpStatus.ok) {
      throw HttpException('${response.statusCode} for $url');
    }
    final text = await response.transform(utf8.decoder).join();
    return [
      for (final line in LineSplitter.split(text))
        if (line.split('#').first.trim() case final data when data.isNotEmpty)
          data.split(';').map((field) => field.trim()).toList(),
    ];
  } finally {
    client.close();
  }
}

int _code(String hex) => int.parse(hex, radix: 16);

String _hex(int code) => code.toRadixString(16).toUpperCase().padLeft(4, '0');
